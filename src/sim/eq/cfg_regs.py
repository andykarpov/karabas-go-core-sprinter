#!/usr/bin/env python3
# tb_cfg_rst: the list of every register of sp_acex and its submodules, taken from the RTL (declarations with a
# power-up value "reg ... x = v"; memories "reg [..] m [0:255]" apart), as a Verilog include:
#   task dirty_regs / dirty_mems  random values into every register / RAM word of the instance <dut>
#   st_<a> / st_<b>               all registers of the two instances, concatenated (compared every CLK)
#   task st_diff                  prints the registers that differ
#   task mem_cmp                  counts the RAM words that differ (mem_bad)
# The reload helpers of CFG_RST itself (rl_*, CFG_DONE) and the MIF copies (ini) are left out.
# usage: cfg_regs.py <rtl/acex dir> <out .vh> <instance a> <instance b>
import re, sys

MODS = [('sp_acex.v', ''), ('sp_video2.v', 'SVIDEO.'), ('sp_dcp.v', 'DECODE.'), ('sp_acceler.v', 'ACC.'),
        ('sp_ay.v', 'AY3.'), ('sp_kbd.v', 'KEYS.'), ('sp_mouse.v', 'MS.')]


def split_top(s):
    out, d, cur = [], 0, ''
    for c in s:
        if c in '({[':
            d += 1
        if c in ')}]':
            d -= 1
        if c == ',' and d == 0:
            out.append(cur)
            cur = ''
        else:
            cur += c
    out.append(cur)
    return out


def scan(path):
    t = re.sub(r'//[^\n]*', '', open(path).read())
    regs, mems = [], []
    for m in re.finditer(r'\b(output\s+)?reg\b\s*(signed\s*)?(\[[^\]]*\])?([^;]*?)(;|\n)', t):
        body = m.group(4)
        if m.group(1):
            body = body.split(',')[0]
        w = 1
        if m.group(3):
            hi, lo = re.match(r'\[\s*(\d+)\s*:\s*(\d+)\s*\]', m.group(3)).groups()
            w = int(hi) - int(lo) + 1
        for item in split_top(body):
            mm = re.match(r'\s*([A-Za-z_]\w*)\s*(\[\s*0\s*:\s*(\d+)\s*\])?\s*(=\s*(.+))?\s*$', item, re.S)
            if not mm:
                continue
            name, arr, depth, _, init = mm.groups()
            if name.startswith('rl_') or name in ('CFG_DONE', 'ini'):
                continue
            if arr:
                mems.append((name, int(depth) + 1, w))
            elif init is not None:
                regs.append((name, w))
    return regs, mems


def main():
    d, out, a, b = sys.argv[1:5]
    regs, mems = [], []
    for f, pre in MODS:
        r, m = scan(d + '/' + f)
        regs += [(pre + n, w) for n, w in r]
        mems += [(pre + n, dep, w) for n, dep, w in m]
    tot = sum(w for _, w in regs)
    o = ['// generated by cfg_regs.py: %d registers (%d bits), %d RAMs' % (len(regs), tot, len(mems))]
    o.append('localparam integer ST_W = %d;' % tot)
    for inst in (a, b):
        o.append('wire [ST_W-1:0] st_%s = {%s};' % (inst, ', '.join('%s.%s' % (inst, n) for n, _ in regs)))
    o.append('task dirty_regs(inout integer s); begin')
    for n, w in regs:
        o.append('\t%s.%s = $random(s);' % (b, n))
    o.append('end endtask')
    o.append('task dirty_mems(inout integer s); integer i; begin')
    for n, dep, w in mems:
        o.append('\tfor (i = 0; i < %d; i = i + 1) %s.%s[i] = $random(s);' % (dep, b, n))
    o.append('end endtask')
    o.append('integer st_shown = 0;')
    o.append('task st_diff; begin')
    for n, w in regs:
        o.append('\tif (%s.%s !== %s.%s && st_shown < 12) begin st_shown = st_shown + 1; '
                 '$display("    reg %s: %s %%h, %s %%h", %s.%s, %s.%s); end' % (a, n, b, n, n, a, b, a, n, b, n))
    o.append('end endtask')
    o.append('integer mem_bad = 0;')
    o.append('task mem_cmp; integer i; begin')
    o.append('\tmem_bad = 0;')
    for n, dep, w in mems:
        o.append('\tfor (i = 0; i < %d; i = i + 1) if (%s.%s[i] !== %s.%s[i]) begin mem_bad = mem_bad + 1; '
                 'if (mem_bad <= 5) $display("    RAM %s[%%0d]: %s %%h, %s %%h", i, %s.%s[i], %s.%s[i]); end'
                 % (dep, a, n, b, n, n, a, b, a, n, b, n))
    o.append('end endtask')
    o.append('initial $display("  cfg_regs: %d registers, %d bits; RAMs: %s");'
             % (len(regs), tot, ', '.join('%s (%d x %d)' % (n, dep, w) for n, dep, w in mems)))
    open(out, 'w').write('\n'.join(o) + '\n')


main()
